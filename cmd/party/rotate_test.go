// rotateEnv points the CLI at the given gatewaytest fake with a fixed
// current party keypair (seed byte i = i, so seed(0) is deterministic).
// Parameters: t is the test harness, gw the fake gateway.
// Returns: the current signing key. Never panics.
func rotateEnv(t *testing.T, gw *gatewaytest.Gateway) ed25519.PrivateKey {
	t.Helper()
	seed := make([]byte, ed25519.SeedSize)
	for i := range seed {
		seed[i] = byte(i)
	}
	encSeed := bytes.Repeat([]byte{0x42}, 32)
	t.Setenv("APP_ENV", "test")
	t.Setenv("APP_GATEWAY_URL", gw.URL())
	t.Setenv("APP_PARTY_ID", "party-test-001")
	t.Setenv("APP_PARTY_PRIVATE_KEY", base64.StdEncoding.EncodeToString(seed))
	t.Setenv("APP_PARTY_ENC_PRIVATE_KEY", base64.StdEncoding.EncodeToString(encSeed))
	return ed25519.NewKeyFromSeed(seed)
}

// TestRotateSubmitsNextKeysSignedWithCurrentAndPrintsNewEnv covers the T14
// contract assertion: rotate against a gatewaytest fake submits the next
// keys signed with the current key and prints the new env values with a
// promote reminder.
// Parameters: t is the test harness.
// Returns: nothing; fails on any deviation.
func TestRotateSubmitsNextKeysSignedWithCurrentAndPrintsNewEnv(t *testing.T) {
	gw := gatewaytest.NewGateway()
	t.Cleanup(gw.Close)
	currentKey := rotateEnv(t, gw)

	var stdout, stderr bytes.Buffer
	require.NoError(t, run([]string{"rotate"}, &stdout, &stderr),
		"rotate must succeed against the gatewaytest fake")
	require.Empty(t, stderr.String(), "rotate must not write to stderr")
	out := stdout.String()

	// Exactly one request reached the fake: the rotate itself.
	recs := gw.Recorded()
	require.Len(t, recs, 1, "rotate must issue exactly one request")
	rot := recs[0]
	require.Equal(t, http.MethodPost, rot.Method)
	require.Equal(t, "/v1/parties/party-test-001/keys", rot.Path)

	// The rotation request is signed with the CURRENT key: the bearer token
	// verifies offline against the current party JWKS.
	require.True(t, strings.HasPrefix(rot.Authorization, "Bearer "),
		"rotate must carry a bearer ks-party+jwt")
	tok := strings.TrimSpace(strings.TrimPrefix(rot.Authorization, "Bearer "))
	currentPub := currentKey.Public().(ed25519.PublicKey)
	jwks, err := gatewaytest.Ed25519JWKS(currentPub)
	require.NoError(t, err)
	srv, err := gatewaytest.NewJWKSServer(jwks)
	require.NoError(t, err)
	t.Cleanup(srv.Close)
	_, err = srv.Verify(tok)
	require.NoError(t, err, "rotate must be signed with the current key")

	// The body carries the NEXT key generated by this rotate run.
	var body struct {
		PublicKey string `json:"public_key"`
		Kid       string `json:"kid"`
		Alg       string `json:"alg"`
	}
	require.NoError(t, json.Unmarshal(rot.Body, &body))
	require.Equal(t, "Ed25519", body.Alg)
	nextKey, err := auth.ParseEd25519PrivateKey(
		envLine(t, out, "APP_PARTY_NEXT_PRIVATE_KEY"))
	require.NoError(t, err, "printed APP_PARTY_NEXT_PRIVATE_KEY must parse with the SDK helper")
	nextPub := nextKey.Public().(ed25519.PublicKey)
	assert.Equal(t, base64.StdEncoding.EncodeToString(nextPub), body.PublicKey,
		"rotate must submit the next signing key it generated")
	assert.NotEqual(t, base64.StdEncoding.EncodeToString(currentPub), body.PublicKey,
		"the next key must differ from the current key")

	// The printed kid is the RFC 7638 thumbprint of the next public key and
	// equals the kid submitted to the gateway (computed independently).
	canonical := `{"crv":"Ed25519","kty":"OKP","x":"` +
		base64.RawURLEncoding.EncodeToString(nextPub) + `"}`
	sum := sha256.Sum256([]byte(canonical))
	wantKid := base64.RawURLEncoding.EncodeToString(sum[:])
	assert.Equal(t, wantKid, envLine(t, out, "kid"),
		"kid must be the RFC 7638 thumbprint of the next signing key")
	assert.Equal(t, wantKid, body.Kid, "the submitted kid must match the printed kid")

	// The printed next enc key parses with the SDK helper and its public
	// half matches the printed enc_public_key.
	nextEnc, err := envelope.ParseX25519PrivateKey(
		envLine(t, out, "APP_PARTY_NEXT_ENC_PRIVATE_KEY"))
	require.NoError(t, err, "printed APP_PARTY_NEXT_ENC_PRIVATE_KEY must parse with the SDK helper")
	assert.Equal(t, base64.StdEncoding.EncodeToString(nextEnc.PublicKey().Bytes()),
		envLine(t, out, "enc_public_key"),
		"enc_public_key must be the base64 X25519 public half")

	// The output ends with the promote reminder.
	assert.Contains(t, strings.ToLower(out), "promote",
		"rotate must print a promote reminder alongside the new env values")
}

// TestRotateGatewayRejectionExitsNonZeroWithMappedError covers the T14
// contract assertion: a gateway rejection makes rotate exit non-zero with
// the mapped error and print no key material.
// Parameters: t is the test harness.
// Returns: nothing; fails on any deviation.
func TestRotateGatewayRejectionExitsNonZeroWithMappedError(t *testing.T) {
	gw := gatewaytest.NewGateway()
	t.Cleanup(gw.Close)
	gw.Script(http.MethodPost, "/v1/parties/{id}/keys", gatewaytest.ScriptStep{
		Status: http.StatusForbidden,
		Body:   []byte(`{"error":{"code":"GW-PARTY-011","message":"superseded key","request_id":"req-party-011"}}`),
	})
	rotateEnv(t, gw)

	var stdout, stderr bytes.Buffer
	err := run([]string{"rotate"}, &stdout, &stderr)
	require.Error(t, err, "a gateway rejection must fail the command (non-zero exit)")

	// The failure surfaces as the mapped error carrying the gateway code.
	var mapped *exceptions.CustomError
	require.ErrorAs(t, err, &mapped, "rotate must return the mapped gateway error")
	assert.Contains(t, err.Error(), "GW-PARTY-011",
		"the mapped error must carry the gateway rejection code")

	// No key material may reach either output stream on failure.
	require.Empty(t, stdout.String(),
		"a rejected rotate must print no key material")
	require.Empty(t, stderr.String(),
		"a rejected rotate must not write to stderr")
}
